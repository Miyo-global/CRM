// Compiles email-templates/<id>.html + <id>.txt into
// lib/email-templates/catalog.generated.ts so renderEmail() needs no file
// access at runtime. Run after editing a template:
//   node scripts/build-email-templates.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "email-templates";
const ids = readdirSync(dir).filter((f) => f.endsWith(".html")).map((f) => f.slice(0, -5)).sort();

const catalog = {};
for (const id of ids) {
  const html = readFileSync(join(dir, `${id}.html`), "utf-8");
  const txt = readFileSync(join(dir, `${id}.txt`), "utf-8").replace(/\r\n/g, "\n");
  const lines = txt.split("\n");
  const header = {};
  let i = 0;
  for (; i < lines.length && /^(Subject|Preheader):/.test(lines[i]); i++) {
    const [key, ...rest] = lines[i].split(":");
    header[key.toLowerCase()] = rest.join(":").trim();
  }
  if (!header.subject) throw new Error(`${id}.txt has no Subject: line`);
  const text = lines.slice(i).join("\n").replace(/^\n+/, "").replace(/\s+$/, "") + "\n";
  catalog[id] = { subject: header.subject, preheader: header.preheader ?? "", html, text };
}

const out = `// Generated by scripts/build-email-templates.mjs from email-templates/. Do not edit.
/* eslint-disable */
export type EmailTemplateId =
${ids.map((id) => `  | ${JSON.stringify(id)}`).join("\n")};

export interface EmailCatalogEntry {
  subject: string;
  preheader: string;
  html: string;
  text: string;
}

export const EMAIL_CATALOG: Record<EmailTemplateId, EmailCatalogEntry> = ${JSON.stringify(catalog, null, 2)};
`;
writeFileSync("lib/email-templates/catalog.generated.ts", out);
console.log(`email templates: ${ids.length}`);
